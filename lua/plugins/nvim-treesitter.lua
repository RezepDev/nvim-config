return {
  {
  "nvim-treesitter/nvim-treesitter",
  lazy = false,    -- Main branch requires immediate initialization
  branch = "main", -- Targeted for Neovim 0.12+
  build = ":TSUpdate",
  config = function()
    local ts = require("nvim-treesitter")

    -- Safely defer parser download so it doesn't freeze or miss early boot cycles
    vim.defer_fn(function()
      ts.install({
        "lua", "vim", "vimdoc", "query", "markdown", 
        "markdown_inline", "cpp", "c"
      })
      ts.update()
    end, 1000)

    -- Define target language hooks
    local ts_langs = { "c", "cpp", "lua", "vim", "markdown" }

    -- Setup structural event rules to bind the highlighting to the buffers
    vim.api.nvim_create_autocmd("FileType", {
      pattern = ts_langs,
      desc = "Trigger native Treesitter highlights",
      callback = function(args)
        pcall(vim.treesitter.start, args.buf)
      end,
    })

    -- Instantly enforce highlights if nvim was booted directly into a file
    local current_buf = vim.api.nvim_get_current_buf()
    local current_ft = vim.bo[current_buf].filetype
    if vim.tbl_contains(ts_langs, current_ft) then
      pcall(vim.treesitter.start, current_buf)
    end
  end,
  },
  -- 2. Text-Objects (Configured independently on its 'main' branch)
  {
  "nvim-treesitter/nvim-treesitter-textobjects",
  branch = "main",
  config = function()
	  require("nvim-treesitter-textobjects").setup {
  select = {
    lookahead = true,
    -- mapping query_strings to modes.
    selection_modes = {
      ['@parameter.outer'] = 'v', -- charwise
      ['@function.outer'] = 'V', -- linewise
      -- ['@class.outer'] = '<c-v>', -- blockwise
    },
    -- If you set this to `true` (default is `false`) then any textobject is
    -- extended to include preceding or succeeding whitespace. Succeeding
    -- whitespace has priority in order to act similarly to eg the built-in
    -- `ap`.
    --
    -- Can also be a function which gets passed a table with the keys
    -- * query_string: eg '@function.inner'
    -- * selection_mode: eg 'v'
    -- and should return true of false
    include_surrounding_whitespace = false,
  },
}

-- keymaps
-- You can use the capture groups defined in `textobjects.scm`
vim.keymap.set({ "x", "o" }, "am", function()
  require "nvim-treesitter-textobjects.select".select_textobject("@function.outer", "textobjects")
end)
vim.keymap.set({ "x", "o" }, "im", function()
  require "nvim-treesitter-textobjects.select".select_textobject("@function.inner", "textobjects")
end)
vim.keymap.set({ "x", "o" }, "ac", function()
  require "nvim-treesitter-textobjects.select".select_textobject("@class.outer", "textobjects")
end)
vim.keymap.set({ "x", "o" }, "ic", function()
  require "nvim-treesitter-textobjects.select".select_textobject("@class.inner", "textobjects")
end)
-- You can also use captures from other query groups like `locals.scm`
vim.keymap.set({ "x", "o" }, "as", function()
  require "nvim-treesitter-textobjects.select".select_textobject("@local.scope", "locals")
end)
-- configuration
require("nvim-treesitter-textobjects").setup {
  move = {
    -- whether to set jumps in the jumplist
    set_jumps = true,
  },
}

-- keymaps
-- You can use the capture groups defined in `textobjects.scm`
vim.keymap.set({ "n", "x", "o" }, "]m", function()
  require("nvim-treesitter-textobjects.move").goto_next_start("@function.outer", "textobjects")
end)
vim.keymap.set({ "n", "x", "o" }, "]]", function()
  require("nvim-treesitter-textobjects.move").goto_next_start("@class.outer", "textobjects")
end)
-- You can also pass a list to group multiple queries.
vim.keymap.set({ "n", "x", "o" }, "]o", function()
  require("nvim-treesitter-textobjects.move").goto_next_start({"@loop.inner", "@loop.outer"}, "textobjects")
end)
-- You can also use captures from other query groups like `locals.scm` or `folds.scm`
vim.keymap.set({ "n", "x", "o" }, "]s", function()
  require("nvim-treesitter-textobjects.move").goto_next_start("@local.scope", "locals")
end)
vim.keymap.set({ "n", "x", "o" }, "]z", function()
  require("nvim-treesitter-textobjects.move").goto_next_start("@fold", "folds")
end)

vim.keymap.set({ "n", "x", "o" }, "]M", function()
  require("nvim-treesitter-textobjects.move").goto_next_end("@function.outer", "textobjects")
